-- ---------------------------------------------------------------------
-- users: 서비스 사용자 (ERD의 User. user는 PostgreSQL 예약어라 users로 둔다)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    -- 1, 2, 3 … 자동 증가. JPA의 GenerationType.IDENTITY와 짝이다.
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,
    -- 인증 제공자가 준 고유 식별자. 같은 사람의 중복 가입을 막는다.
    auth_subject    VARCHAR(255) NOT NULL UNIQUE,
    -- 아래 점검 입력값은 직접 입력 여부가 미정이라 모두 NULL 허용
    birth_year      INTEGER,
    joined_on       DATE,
    is_sme_employee BOOLEAN,
    terms_version   VARCHAR(255),
    consented_at    TIMESTAMPTZ
);

-- ---------------------------------------------------------------------
-- payslip: 업로드한 급여명세서 1건 (원본 파일은 저장하지 않는다)
-- ---------------------------------------------------------------------
CREATE TABLE payslip (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at     TIMESTAMPTZ  NOT NULL,
    updated_at     TIMESTAMPTZ  NOT NULL,
    -- ON DELETE RESTRICT: 명세서가 남아 있는 사용자는 지울 수 없다(실수로 데이터가 사라지는 것 방지).
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    -- 귀속 월 "YYYY-MM". DB에서도 형식을 한 번 더 막는다.
    pay_period     VARCHAR(7)   NOT NULL CHECK (pay_period ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    company_name   VARCHAR(255),
    -- 표준 필드로 못 맞춘 항목 [{ "label": ..., "amount": ... }]
    unmapped_items JSONB        NOT NULL DEFAULT '[]'::jsonb,
    -- 검증 경고 [{ "field": ..., "reason": ... }]
    warnings       JSONB        NOT NULL DEFAULT '[]'::jsonb
);
CREATE INDEX idx_payslip_user_pay_period ON payslip (user_id, pay_period);

-- ---------------------------------------------------------------------
-- payslip_field: 명세서의 표준 필드 1칸 (필드는 열이 아니라 행)
-- ---------------------------------------------------------------------
CREATE TABLE payslip_field (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ON DELETE CASCADE: 명세서를 지우면 필드도 함께 지운다.
    payslip_id     BIGINT       NOT NULL REFERENCES payslip (id) ON DELETE CASCADE,
    -- PayslipFieldKey enum 이름(BASE_SALARY 등). EnumType.STRING과 짝이다.
    key            VARCHAR(40)  NOT NULL CHECK (key IN (
                       'BASE_SALARY', 'MEAL_ALLOWANCE', 'CAR_ALLOWANCE', 'OVERTIME_PAY', 'BONUS', 'PAYMENT_TOTAL',
                       'NATIONAL_PENSION', 'HEALTH_INSURANCE', 'LONG_TERM_CARE', 'EMPLOYMENT_INSURANCE',
                       'INCOME_TAX', 'LOCAL_INCOME_TAX', 'DEDUCTION_TOTAL', 'NET_PAY')),
    -- 월 기준 원 단위. 못 읽었으면 NULL(0과 구분)
    value          INTEGER,
    confidence     DOUBLE PRECISION CHECK (confidence BETWEEN 0 AND 1),
    source_label   VARCHAR(255),
    status         VARCHAR(20)  NOT NULL CHECK (status IN ('OK', 'NEEDS_REVIEW', 'MISSING')),
    user_confirmed BOOLEAN      NOT NULL DEFAULT FALSE,
    -- 같은 명세서에 같은 필드는 하나만
    CONSTRAINT uk_payslip_field_payslip_key UNIQUE (payslip_id, key)
);

-- ---------------------------------------------------------------------
-- tax_rule_version: 점검 규칙 버전
-- ---------------------------------------------------------------------
CREATE TABLE tax_rule_version (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    tax_year    INTEGER      NOT NULL,
    version     VARCHAR(255) NOT NULL,
    status      VARCHAR(20)  NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'VERIFIED')),
    parameters  JSONB        NOT NULL,
    source_url  VARCHAR(255),
    verified_at TIMESTAMPTZ,
    CONSTRAINT uk_tax_rule_version_year_version UNIQUE (tax_year, version),
    -- VERIFIED인데 출처나 검증 시각이 없는 상태를 DB에서도 막는다.
    CONSTRAINT ck_tax_rule_version_verified
        CHECK (status <> 'VERIFIED' OR (source_url IS NOT NULL AND verified_at IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- check_finding: 점검 결과 1건 (만든 뒤 수정하지 않으므로 updated_at 없음)
-- ---------------------------------------------------------------------
CREATE TABLE check_finding (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at          TIMESTAMPTZ  NOT NULL,
    payslip_id          BIGINT       NOT NULL REFERENCES payslip (id) ON DELETE RESTRICT,
    tax_rule_version_id BIGINT       NOT NULL REFERENCES tax_rule_version (id) ON DELETE RESTRICT,
    rule_code           VARCHAR(100) NOT NULL,
    severity            VARCHAR(20)  NOT NULL CHECK (severity IN ('INFO', 'WARNING', 'CRITICAL')),
    message             TEXT         NOT NULL,
    -- 항상 예상치 안내
    is_estimate         BOOLEAN      NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_check_finding_payslip ON check_finding (payslip_id);
CREATE INDEX idx_check_finding_tax_rule_version ON check_finding (tax_rule_version_id);

-- ---------------------------------------------------------------------
-- task_template: 할 일 원본(틀)
-- ---------------------------------------------------------------------
CREATE TABLE task_template (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ  NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL,
    key         VARCHAR(100) NOT NULL UNIQUE,
    title       VARCHAR(255) NOT NULL,
    description TEXT,
    due_rule    VARCHAR(100) NOT NULL
);

-- ---------------------------------------------------------------------
-- user_task: 사용자별 할 일
-- ---------------------------------------------------------------------
CREATE TABLE user_task (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL,
    updated_at  TIMESTAMPTZ NOT NULL,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    template_id BIGINT      NOT NULL REFERENCES task_template (id) ON DELETE RESTRICT,
    -- ON DELETE SET NULL: 점검 결과가 지워져도 할 일은 남기고 연결만 끊는다.
    finding_id  BIGINT               REFERENCES check_finding (id) ON DELETE SET NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'TODO' CHECK (status IN ('TODO', 'DONE', 'NOT_APPLICABLE')),
    due_on      DATE,
    -- 같은 사용자는 같은 템플릿을 한 번만 받는다
    CONSTRAINT uk_user_task_user_template UNIQUE (user_id, template_id)
);
CREATE INDEX idx_user_task_finding ON user_task (finding_id);
