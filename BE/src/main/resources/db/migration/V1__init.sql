--       스키마를 바꾸려면 V2__설명.sql 처럼 새 파일을 추가한다.
--
-- JPA 엔티티(ddl-auto: validate)는 이 테이블들이 엔티티와 맞는지만 검사한다.
-- 컬럼 이름·타입을 바꾸면 엔티티와 이 SQL(다음 버전 파일)을 함께 바꿔야 한다.
