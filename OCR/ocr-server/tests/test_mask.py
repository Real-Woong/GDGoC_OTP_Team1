"""개인정보 탐지 규칙 테스트 (이미지 없이 글자만으로). 모든 번호는 가짜입니다."""

import pytest

from ocr.mask import detect
from ocr.recognize import TextBox


def box(text, x0=0, y0=0, x1=300, y1=40):
    return TextBox(text, 0.99, x0, y0, x1, y1)


def kinds(boxes):
    return sorted(k for k, *_ in detect(boxes))


# (설명, 박스 목록, 기대하는 탐지 종류)
CASES = [
    # ---- 주민등록번호 ----
    ("주민번호 하이픈", [box("990101-1234567")], ["주민등록번호"]),
    ("주민번호 하이픈 없음", [box("9901011234567")], ["주민등록번호"]),
    ("주민번호 뒷자리 가림", [box("990101-1******")], ["주민등록번호"]),
    ("주민번호 문장 속", [box("주민등록번호: 020820-3000000")], ["주민등록번호"]),
    ("주민번호 아님: 13월", [box("991301-1234567")], []),
    ("주민번호 아님: 성별자리 9", [box("990101-9234567")], []),
    # ---- 전화번호 ----
    ("휴대폰 하이픈", [box("010-1234-5678")], ["전화번호"]),
    ("휴대폰 붙여쓰기", [box("01012345678")], ["전화번호"]),
    ("서울 지역번호", [box("02-345-6789")], ["전화번호"]),
    ("지역번호 점 구분", [box("031.123.4567")], ["전화번호"]),
    ("인터넷전화", [box("연락처 070-1234-5678")], ["전화번호"]),
    # ---- 이메일 ----
    ("이메일", [box("문의: pay.team@example.co.kr")], ["이메일"]),
    # ---- 계좌번호 (라벨 기준) ----
    ("같은 박스: 은행명+번호", [box("예시은행 000-0000-0000-00")], ["계좌번호"]),
    ("같은 박스: 라벨+번호", [box("지급계좌: 국민 123-45-678901")], ["계좌번호"]),
    ("같은 줄 오른쪽 칸", [box("지급계좌", 0, 0, 100, 40), box("111-22-333333", 150, 2, 400, 38)], ["계좌번호"]),
    ("라벨 바로 아래 줄", [box("입금계좌", 0, 0, 100, 40), box("9999-00-123456", 0, 50, 220, 90)], ["계좌번호"]),
    ("라벨 없는 숫자는 계좌로 보지 않음", [box("321-654-987000")], []),
    ("라벨 옆이라도 짧으면 아님(9자리)", [box("지급계좌", 0, 0, 100, 40), box("123-45-6789", 150, 2, 400, 38)], []),
    ("라벨 옆이라도 너무 길면 아님(15자리)", [box("계좌", 0, 0, 100, 40), box("123456789012345", 150, 2, 400, 38)], []),
    ("다른 줄의 금액은 계좌 아님",
     [box("지급계좌", 0, 0, 100, 40), box("예시은행", 150, 2, 300, 38), box("3,150,000", 150, 300, 300, 340)], []),
    # ---- 잡으면 안 되는 것 ----
    ("날짜", [box("지급일 2026-03-25")], []),
    ("금액", [box("3,150,000")], []),
    ("사번", [box("20250312")], []),
    ("사번 영문", [box("A-1024")], []),
    ("성명은 탐지하지 않음", [box("김예시")], []),
    ("주소는 탐지하지 않음", [box("서울시 예시구 예시로 12")], []),
    # ---- 한 박스에 여러 개 ----
    ("전화+이메일", [box("010-1234-5678 / a@b.com")], ["이메일", "전화번호"]),
]


@pytest.mark.parametrize("name,boxes,expected", CASES, ids=[c[0] for c in CASES])
def test_detect(name, boxes, expected):
    assert kinds(boxes) == sorted(expected)
