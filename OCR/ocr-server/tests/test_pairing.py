"""항목명-금액 짝짓기 규칙 테스트 (이미지 없이 박스 좌표만으로)."""

import pytest

from ocr.pairing import pair, parse_amount
from ocr.recognize import TextBox

H = 30  # 기본 박스 높이


def box(text, x, y, w=120, h=H):
    return TextBox(text, 0.99, x, y, x + w, y + h)


def pairs_of(boxes):
    r = pair(boxes)
    return [(p.label, p.amount) for p in r.pairs], [b.text for b in r.unmatched_amounts]


RESULTS = []  # (이름, 결과, 기대값). 아래 check 호출이 모으고 맨 끝 테스트 함수가 하나씩 확인한다


def check(name, got, expected):
    RESULTS.append((name, got, expected))


# ---- 금액 판별 ----
for text, expected in [
    ("2,800,000", 2800000), ("980", 980), ("0", 0), ("131,.630", 131630), ("1.354.830", 1354830),
    ("3,000,000원", 3000000), ("-12,000", -12000), ("△12,000", -12000), (" 200,000 ", 200000),
    ("20250312", None), ("2025-03-12", None), ("[계좌번호]", None), ("1,23", None), ("기본급", None),
    ("A-1024", None), ("12,34,567", None),
]:
    check(f"금액 판별 {text!r}", parse_amount(text), expected)

# ---- 1단 양식 ----
check("1단: 항목|금액",
      pairs_of([box("기본급", 0, 100), box("2,800,000", 800, 100),
                box("식대", 0, 150), box("200,000", 800, 150)]),
      ([("기본급", 2800000), ("식대", 200000)], []))

# ---- 2단 양식 ----
check("2단: 항목|금액|항목|금액",
      pairs_of([box("기본급", 0, 100), box("3,200,000", 300, 100), box("국민연금", 500, 100), box("160,550", 800, 100)]),
      ([("기본급", 3200000), ("국민연금", 160550)], []))
check("2단: 왼쪽 칸이 빈 행",
      pairs_of([box("소득세", 500, 100), box("112,000", 800, 100)]),
      ([("소득세", 112000)], []))

# ---- 표 제목·인적사항은 짝이 생기지 않아야 함 ----
check("표 제목 행", pairs_of([box("지급항목", 0, 50), box("금액(원)", 800, 50)]), ([], []))
check("사번(쉼표 없는 숫자)", pairs_of([box("사번", 0, 50), box("20250312", 300, 50)]), ([], []))
check("입사일(날짜)", pairs_of([box("입사일", 0, 50), box("2025-03-12", 300, 50)]), ([], []))
check("마스킹 값", pairs_of([box("지급계좌", 0, 50), box("예시은행[계좌번호]", 300, 50)]), ([], []))
check("날짜 뒤 금액은 앞 항목과 짝 안 됨",
      pairs_of([box("입사일", 0, 50), box("2025-03-12", 200, 50), box("50,000", 600, 50)]),
      ([], ["50,000"]))

# ---- 행 묶기: 높이 비례 허용 오차 ----
check("살짝 어긋난 행(높이의 40%)",
      pairs_of([box("기본급", 0, 100), box("2,800,000", 800, 100 + int(H * 0.4))]),
      ([("기본급", 2800000)], []))
check("다음 행은 섞이지 않음(높이의 100%)",
      pairs_of([box("기본급", 0, 100), box("2,800,000", 800, 100 + H)]),
      ([], ["2,800,000"]))
check("기울어진 행이 다음 행까지 이어지지 않음",
      # 한 행 안에서 박스마다 0.4H씩 내려가는 사진. 행 평균과 비교하므로 다음 행과 섞이지 않아야 함
      pairs_of([box("기본급", 0, 100), box("2,800,000", 300, 112), box("국민연금", 500, 124),
                box("140,120", 800, 136),
                box("식대", 0, 100 + 2 * H), box("200,000", 300, 112 + 2 * H)]),
      ([("기본급", 2800000), ("국민연금", 140120), ("식대", 200000)], []))
check("큰 사진(박스 높이 2배)에서도 같은 규칙",
      pairs_of([box("기본급", 0, 200, h=60), box("2,800,000", 800, 220, h=60)]),
      ([("기본급", 2800000)], []))

# ---- 한 박스에 붙어 나온 경우 ----
check("붙은 박스: '기본급 2,800,000'", pairs_of([box("기본급 2,800,000", 0, 100, w=400)]), ([("기본급", 2800000)], []))
check("붙은 박스: '식대200,000원'", pairs_of([box("식대200,000원", 0, 100, w=300)]), ([("식대", 200000)], []))
check("붙은 박스로 보면 안 되는 문장",
      pairs_of([box("※3/18 입사,3/18~3/31일할계산(월 기본급3,000,000원)", 0, 100, w=700)]), ([], []))

check("붙은 박스로 보면 안 되는 사번 'A-1024'", pairs_of([box("A-1024", 0, 100)]), ([], []))
check("붙은 박스로 보면 안 되는 날짜",
      pairs_of([box("(주)가나다테크·귀속2026년3월·지급일2026-03-25", 0, 100, w=600)]), ([], []))
check("붙은 박스: 공백 뒤 마이너스 금액", pairs_of([box("소득세환급 -12,000", 0, 100, w=400)]), ([("소득세환급", -12000)], []))

# ---- 짝 없는 금액 ----
check("항목명 없는 금액은 따로 모음", pairs_of([box("1,313,520", 800, 100)]), ([], ["1,313,520"]))

@pytest.mark.parametrize("name,got,expected", RESULTS, ids=[r[0] for r in RESULTS])
def test_pairing(name, got, expected):
    assert got == expected
